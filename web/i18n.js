// Console language support. Chinese is the source language: UI strings are
// written in Chinese in app.js / presets.js and wrapped in t(); I18N_EN maps
// each exact Chinese source string to its English text. Placeholders like
// {n} are filled from the vars object in both languages. HTML markup in a
// value must match the source string.
//
// scripts/check-i18n.mjs verifies that every t() string has an entry here.

const LANG_KEY = 'ai_route_lang';
const LANG = (() => {
  let saved = '';
  try { saved = localStorage.getItem(LANG_KEY) || ''; } catch (e) { /* storage unavailable */ }
  if (saved === 'zh' || saved === 'en') return saved;
  const nav = (typeof navigator !== 'undefined' && navigator.language) || '';
  return nav.toLowerCase().startsWith('zh') ? 'zh' : 'en';
})();

function t(zh, vars) {
  let s = zh;
  if (LANG === 'en' && Object.prototype.hasOwnProperty.call(I18N_EN, zh)) s = I18N_EN[zh];
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (Object.prototype.hasOwnProperty.call(vars, k) ? String(vars[k]) : m));
  return s;
}

function setLang(l) {
  if (l !== 'zh' && l !== 'en') return;
  try { localStorage.setItem(LANG_KEY, l); } catch (e) { /* storage unavailable */ }
  location.reload();
}

// "中文 | English" switch; bindLangSwitch wires the buttons inside root.
function langSwitchHTML() {
  return `<div class="seg lang-switch" role="group" aria-label="Language">${[['zh', '中文'], ['en', 'English']]
    .map(([l, label]) => `<button type="button" data-lang="${l}" class="${LANG === l ? 'on' : ''}" lang="${l === 'zh' ? 'zh-CN' : 'en'}">${label}</button>`).join('')}</div>`;
}
function bindLangSwitch(root) {
  root.querySelectorAll('[data-lang]').forEach((b) => { b.onclick = () => { if (b.dataset.lang !== LANG) setLang(b.dataset.lang); }; });
}

